#pragma once
/* Подсистема памяти ядра (C2): куча, адресные пространства, самотест.
 * Приватный заголовок ядра: драйверы его не видят. Всё, что нужно драйверам, живёт в include/miga/mem.h. */
#include <stdint.h>
#include <stddef.h>

/* Физический <-> виртуальный адрес. Пока ядро работает в identity map, это тождество.
 * Весь код mm/ обязан ходить к памяти по физическому адресу ТОЛЬКО через эти макросы:
 * при переносе ядра в высокую половину поменяются лишь они. */
#define P2V(pa) ((void *)(uintptr_t)(pa))
#define V2P(p)  ((uint64_t)(uintptr_t)(p))

/* ------------------------------------------------------------------ куча ядра */
/* Выравнивание результата 16 байт. Память kmalloc НЕ обнуляется (kzalloc обнуляет).
 * kmalloc(0) возвращает валидный минимальный блок. NULL = нет памяти или слишком большой запрос.
 * Можно звать из обработчиков прерываний (внутри cpu_irq_save), но не раньше pmm_init(). */
void *kmalloc(size_t n);
void *kzalloc(size_t n);
void  kfree(void *p);                 /* kfree(NULL) допустим; чужой указатель и двойное освобождение = panic */

struct kheap_stats {
    uint64_t live_allocs;             /* сейчас выделено блоков */
    uint64_t live_bytes;              /* их полезный размер (размер класса / страницы крупного блока минус заголовок) */
    uint64_t total_allocs, total_frees;
    uint64_t slab_pages;              /* страниц PMM, занятых размерными классами */
    uint64_t large_pages;             /* страниц PMM, занятых крупными блоками */
};
void kheap_stats_get(struct kheap_stats *s);
void kheap_trim(void);                /* вернуть PMM пустые закэшированные страницы размерных классов */

/* ------------------------------------------------------------------ DMA */
void dma_free_page(void *p);          /* парный к dma_alloc_page(); в include/miga/mem.h попадёт через запрос к C1 */

/* ------------------------------------------------------------------ адресные пространства (vmm.c) */
/* Раскладка виртуальных адресов (индексы записей PML4 по 512 ГиБ):
 *   [0..127]    ядро: identity map RAM и MMIO (paging.c, mmio_map). Общая для всех пространств, vm_map сюда не пишет.
 *   [128..255]  пользователь: VA от 64 ТиБ до 128 ТиБ. Своя в каждом пространстве.
 *   [256..511]  верхняя половина: ядро (vm_map без VM_USER). Общая для всех пространств.
 * «Общая» значит: записи PML4 копируются при создании и при любом изменении синхронизируются во ВСЕ пространства,
 * созданные через vm_space_create (нижние уровни таблиц и так общие по указателю). */
#define VM_USER_BASE    0x0000400000000000ULL
#define VM_USER_END     0x0000800000000000ULL
#define VM_KERNEL_BASE  0xFFFF800000000000ULL

#define VM_WRITE    1u      /* страница доступна на запись */
#define VM_USER     2u      /* доступна из кольца 3 (иначе только ядру) */
#define VM_NOEXEC   4u      /* запрет исполнения. Если CPU не поддерживает NX (vm_nx_enabled() == 0), флаг игнорируется */

#define VM_FREE_FRAMES 1u   /* vm_space_destroy: вернуть PMM и сами отображённые кадры, не только таблицы страниц */

#define VM_OK       0
#define VM_E_INVAL  (-1)    /* неверный аргумент: не выровнено, не тот диапазон адресов, huge-страница */
#define VM_E_NOMEM  (-2)
#define VM_E_EXIST  (-3)    /* по этому адресу уже что-то отображено */
#define VM_E_NOENT  (-4)    /* по этому адресу ничего нет */

/* Пространство = физический адрес его PML4 (то, что кладут в CR3). 0 = ошибка/нет пространства. */
uint64_t vm_kernel_cr3(void);                       /* главная PML4 ядра (paging.c) */
uint64_t vm_space_create(void);                     /* новое пространство: ядерные половины общие, пользовательская пуста */
void     vm_space_destroy(uint64_t cr3, unsigned flags); /* освободить таблицы (и кадры при VM_FREE_FRAMES); нельзя для активного CR3 */
int      vm_map(uint64_t cr3, uint64_t va, uint64_t pa, unsigned flags);   /* одна страница 4 КиБ */
int      vm_unmap(uint64_t cr3, uint64_t va, uint64_t *pa_out);            /* pa_out может быть NULL; кадр НЕ освобождается */
int      vm_query(uint64_t cr3, uint64_t va, uint64_t *pa_out, unsigned *flags_out); /* понимает и huge-страницы identity map */
int      vm_nx_enabled(void);                       /* 1, если EFER.NXE включён */
void     vm_kernel_pml4e_set(unsigned idx, uint64_t val); /* для paging.c: новая ядерная запись PML4 во все пространства */

/* ------------------------------------------------------------------ самотест */
/* Печатает "SELFTEST mm OK" или "SELFTEST mm FAIL" (плюс причины). Возвращает 0 при успехе.
 * Запускается сам стадией DRV_NORMAL (см. mmtest.c), отдельно вызывать не нужно. */
int mm_selftest(void);
